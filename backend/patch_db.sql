-- 3. Patch LISTINGS Table
DECLARE
    column_exists EXCEPTION;
    PRAGMA EXCEPTION_INIT(column_exists, -01430);
BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE LISTINGS ADD LOCATION VARCHAR2(255)';
    EXECUTE IMMEDIATE 'ALTER TABLE LISTINGS ADD ITEM_CONDITION VARCHAR2(50)';
    EXECUTE IMMEDIATE 'ALTER TABLE LISTINGS ADD CATEGORY_ID NUMBER';
    EXECUTE IMMEDIATE 'ALTER TABLE LISTINGS ADD SELLER_ID NUMBER'; 
    EXECUTE IMMEDIATE 'ALTER TABLE LISTINGS ADD CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP';
    DBMS_OUTPUT.PUT_LINE('Altered LISTINGS table.');
EXCEPTION
    WHEN column_exists THEN
        DBMS_OUTPUT.PUT_LINE('Some columns already exist in LISTINGS.');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Error altering LISTINGS: ' || SQLERRM);
END;
/

