
-- Suppress output for missing table drops implicitly
SET SERVEROUTPUT ON;

-- 1. USERS table
DECLARE
  v_count NUMBER;
BEGIN
  SELECT count(*) INTO v_count FROM user_tables WHERE table_name = 'USERS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE SEQUENCE USERS_SEQ START WITH 1 INCREMENT BY 1';
    EXECUTE IMMEDIATE 'CREATE TABLE USERS (
        ID NUMBER DEFAULT USERS_SEQ.NEXTVAL PRIMARY KEY,
        USERNAME VARCHAR2(50) NOT NULL UNIQUE,
        EMAIL VARCHAR2(100) NOT NULL UNIQUE,
        PASSWORD VARCHAR2(255) NOT NULL,
        PHONE VARCHAR2(20),
        PROFILE_PICTURE VARCHAR2(500),
        CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )';
    DBMS_OUTPUT.PUT_LINE('Created USERS table.');
  ELSE
    DBMS_OUTPUT.PUT_LINE('USERS table already exists.');
  END IF;
END;
/

